def sanitize_vietnamese_ai_keyword(text: str) -> str:
    """
    Thay thế chữ 'AI' hoặc 'ai' đứng độc lập trong câu/tiêu đề tiếng Việt thành nhãn trung tính [***]
    nhằm triệt tiêu thiên kiến từ khóa (priming bias) cho mô hình LLM.
    """
    if not text:
        return ""
    return re.sub(r"\b[aA][iI]\b", "[***]", text)


def clean_forensic_metadata(metadata: dict[str, Any] | None) -> dict[str, Any]:
    """
    Làm sạch siêu dữ liệu truyền vào LLM (Thử nghiệm mù âm học thông minh):
    Gọt bỏ các mác hãng đĩa (Distributor), kênh '- Topic', 'Provided to YouTube by...',
    credit Producer/Composer tự xưng nhằm ngăn ngừa thiên kiến neo nhận thức (Anchor Bias).
    """
    if not metadata:
        return {}
    cleaned = dict(metadata)

    # 1. Làm sạch uploader / channel (loại bỏ - Topic, Official, Channel, VEVO)
    for field in ["uploader", "channel"]:
        val = str(cleaned.get(field) or "").strip()
        if val:
            val = re.sub(r"\s*-\s*topic\b", "", val, flags=re.IGNORECASE)
            val = re.sub(r"\b(topic|official|channel|vevo)\b", "", val, flags=re.IGNORECASE).strip()
            cleaned[field] = val

    # 2. Làm sạch description: Loại bỏ các mẫu tự động từ nhà phân phối số
    desc = str(cleaned.get("description") or "")
    if desc:
        desc = re.sub(r"Provided to YouTube by [^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Auto-generated by YouTube\.?", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"℗\s*\d{4}\s*[^\n]+", "", desc)
        desc = re.sub(r"Released on:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Producer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Composer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Lyricist:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Mastering Engineer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Mixing Engineer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)

        distributors = [
            "Symphonic Distribution",
            "DistroKid",
            "ONErpm",
            "Believe",
            "Warner Music Vietnam",
            "WM Vietnam",
            "INCOM",
            "Mixus",
            "EDM.ASIA",
            "ALINETTEVN MUSIC",
            "CELEB LABELS",
            "TTE Fast Considerate",
            "Sconnect Music",
            "BMZ Music",
            "12 trái lê",
            "COLLAB MUSIC GROUP",
        ]
        for dist in distributors:
            desc = re.sub(rf"\b{re.escape(dist)}\b", "", desc, flags=re.IGNORECASE)

        lines = [line.strip() for line in desc.splitlines() if line.strip()]
        cleaned["description"] = "\n".join(lines)

    return cleaned


class GeminiResponseSchema(BaseModel):
    verdict_type: str = Field(
        description="One of 5 labels: 'CONFIRMED_HUMAN' (100% human organic acoustic), 'PROCESSED_HUMAN' (100% human artist & 100% human beat with modern studio production/Auto-tune), 'HYBRID_AI' (ANY AI participation: AI beat + human voice, or AI voice + human beat, or AI remix), 'AI_GENERATED' (fully AI generated via Suno/Udio), 'UNCERTAIN' (inconclusive evidence, severe noise/distortion, or conflicting indicators)"
    )
    is_ai: bool = Field(
        description="MANDATORY: True if 'AI_GENERATED' or 'HYBRID_AI' (ANY AI involvement in beat, vocal, or composition). False ONLY if 100% human-created ('CONFIRMED_HUMAN', 'PROCESSED_HUMAN'), or 'UNCERTAIN'."
    )
    confidence_score: float = Field(description="Confidence score ranging from 0.0 to 1.0")
    suspected_engine: str = Field(
        description="Suspected platform/model: 'Suno', 'Udio', 'Stable Audio', or 'None'"
    )
    reasons: list[str] = Field(
        description="2-4 sharp, objective bullet points justifying the verdict. MANDATORY FOR HYBRID_AI: The FIRST reason MUST strictly begin with: '[HYBRID AI]: Thành phần Vocal là [Người thật/AI] | Thành phần Beat/Hòa âm là [AI sinh tự động/Người làm] - [Giải thích chi tiết dấu vết kỹ thuật]'"
    )
    detailed_explanation: str = Field(
        description="In-depth technical forensic analysis covering vocal timbre, frequency spectrum, and studio effects vs AI artifacts"
    )


