"""Các hàm tiện ích dùng chung trong toàn bộ hệ thống MusicIdentify.

Đảm bảo tuân thủ nghiêm ngặt PEP 8, Ruff và FAANG Clean Architecture:
- Không lặp lại mã nguồn (DRY Principle)
- Xử lý chuỗi Unicode tiếng Việt an toàn
- Làm sạch dữ liệu và tương thích xuất báo cáo
"""

from __future__ import annotations

import re
import unicodedata
from typing import Any


def normalize_vietnamese_text(text: str, remove_special_chars: bool = False) -> str:
    """Loại bỏ dấu tiếng Việt chuẩn Unicode NFKD và chuẩn hóa khoảng trắng.

    Parameters:
        text: Chuỗi văn bản tiếng Việt đầu vào.
        remove_special_chars: Nếu True, loại bỏ ký tự đặc biệt (giữ lại chữ và số).
    """
    if not text:
        return ""
    text_norm = unicodedata.normalize("NFKD", text)
    without_diacritics = "".join(c for c in text_norm if not unicodedata.combining(c))
    without_diacritics = without_diacritics.replace("đ", "d").replace("Đ", "d")

    if remove_special_chars:
        cleaned = re.sub(r"[^\w\s]", " ", without_diacritics.lower())
        return " ".join(cleaned.split())

    return " ".join(without_diacritics.split()).strip()


def extract_first_entry(entries: Any) -> dict[str, Any] | None:
    """Trích xuất phần tử đầu tiên từ entries của yt-dlp (hỗ trợ list, PagedList và Generator)."""
    if not entries:
        return None
    try:
        entry = entries[0]
        return dict(entry) if isinstance(entry, dict) else None
    except (IndexError, TypeError, KeyError):
        try:
            entry = next(iter(entries))
            return dict(entry) if isinstance(entry, dict) else None
        except (StopIteration, TypeError):
            return None


ILLEGAL_CHARACTERS_RE = re.compile(r"[\000-\010]|[\013-\014]|[\016-\037]")
ANSI_ESCAPE_RE = re.compile(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")


def clean_excel_text(val: Any) -> Any:
    """Lọc bỏ ANSI escape codes, các ký tự điều khiển không hợp lệ và phòng chống CSV/Excel Formula Injection."""
    if val is None:
        return ""
    if isinstance(val, (int, float, bool)):
        return val

    if isinstance(val, str):
        val = ANSI_ESCAPE_RE.sub("", val)
        val = ILLEGAL_CHARACTERS_RE.sub("", val).strip()
        if val and val[0] in ("=", "+", "-", "@"):
            return f"'{val}"
    return val


def sanitize_vietnamese_ai_keyword(text: str) -> str:
    """Thay thế chữ 'AI' hoặc 'ai' đứng độc lập trong câu thành nhãn trung tính [***]

    nhằm triệt tiêu thiên kiến từ khóa (priming bias) cho mô hình LLM.
    """
    if not text:
        return ""
    return re.sub(r"\b[aA][iI]\b", "[***]", text)


def clean_forensic_metadata(metadata: dict[str, Any] | None) -> dict[str, Any]:
    """Làm sạch siêu dữ liệu truyền vào LLM:

    Gọt bỏ các mác hãng đĩa (Distributor), kênh '- Topic', 'Provided to YouTube by...',
    credit Producer/Composer tự xưng nhằm ngăn ngừa thiên kiến neo nhận thức (Anchor Bias).
    """
    if not metadata:
        return {}
    cleaned = dict(metadata)

    # 1. Làm sạch uploader / channel (loại bỏ - Topic, Official, Channel, VEVO)
    for field in ["uploader", "channel"]:
        val = str(cleaned.get(field) or "").strip()
        if val:
            val = re.sub(r"\s*-\s*topic\b", "", val, flags=re.IGNORECASE)
            val = re.sub(r"\b(topic|official|channel|vevo)\b", "", val, flags=re.IGNORECASE).strip()
            cleaned[field] = val

    # 2. Làm sạch description: Loại bỏ các mẫu tự động từ nhà phân phối số
    desc = str(cleaned.get("description") or "")
    if desc:
        desc = re.sub(r"Provided to YouTube by [^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Auto-generated by YouTube\.?", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"℗\s*\d{4}\s*[^\n]+", "", desc)
        desc = re.sub(r"Released on:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Producer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Composer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Lyricist:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Mastering Engineer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)
        desc = re.sub(r"Mixing Engineer:\s*[^\n]+", "", desc, flags=re.IGNORECASE)

        distributors = [
            "Symphonic Distribution",
            "DistroKid",
            "ONErpm",
            "Believe",
            "Warner Music Vietnam",
            "WM Vietnam",
            "INCOM",
            "Mixus",
            "EDM.ASIA",
            "ALINETTEVN MUSIC",
            "CELEB LABELS",
            "TTE Fast Considerate",
            "Sconnect Music",
            "BMZ Music",
            "12 trái lê",
            "COLLAB MUSIC GROUP",
        ]
        for dist in distributors:
            desc = re.sub(rf"\b{re.escape(dist)}\b", "", desc, flags=re.IGNORECASE)

        lines = [line.strip() for line in desc.splitlines() if line.strip()]
        cleaned["description"] = "\n".join(lines)

    return cleaned
