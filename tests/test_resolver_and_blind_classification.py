"""Bộ kiểm thử đảm bảo giải quyết dứt điểm các lỗi lệch nguồn, khử định kiến siêu dữ liệu
và nhận diện chính xác nhạc AI hiện đại.

Kiểm tra:
1. validate_match: Ngăn chặn triệt để hiện tượng trùng tên nghệ sĩ con (subset token mismatch):
   Ví dụ 'Anh Vũ' KHÔNG ĐƯỢC PHÉP khớp với 'Anh Tuấn Vũ' hay 'Phi Thanh'.
2. resolve_track: Ưu tiên tìm kiếm Zing MP3 trước cho các bài hát có chỉ định nghệ sĩ,
   chỉ fallback sang YouTube khi Zing MP3 không có hoặc bị khóa VIP.
3. clean_forensic_metadata: Lọc sạch các câu chữ gây thiên kiến hãng đĩa / Topic
   như 'Provided to YouTube by...', 'Auto-generated by YouTube', tên distributor.
4. Gemini Prompt: Hướng dẫn phân biệt AI hiện đại (Suno v3.5/v4, Lo-fi AI beat, AI Voice Clone)
   và ưu tiên đưa vào HYBRID_AI khi có dấu hiệu can thiệp nhân tạo.

Tuân thủ nghiêm ngặt PEP 8 và Ruff.
"""

from __future__ import annotations

import unittest
from unittest.mock import MagicMock, patch

from backend.core.utils import clean_forensic_metadata
from backend.services.gemini_classifier_service import (
    GeminiClassifierService,
)
from backend.services.resolver_service import InputResolverService


class TestResolverAndBlindClassification(unittest.TestCase):
    """Kiểm thử chuẩn TDD cho Resolver và Phân loại mù âm học."""

    def setUp(self) -> None:
        self.resolver = InputResolverService()
        self.classifier = GeminiClassifierService(api_keys=["fake_test_key_123"])

    def test_validate_match_rejects_artist_name_impersonation(self) -> None:
        """Thuật toán validate_match PHẢI TỪ CHỐI khi tên nghệ sĩ bị nhầm lẫn con (subset)."""
        # Ca sĩ mục tiêu: 'Anh Vũ' (Nghệ sĩ AI độc lập)
        # Ca sĩ trên YouTube: 'Anh Tuan Vu' (Ca sĩ hải ngoại Tuấn Vũ người thật)
        candidate_tuan_vu = {
            "title": "Ly cà phê đắng _ Tuan Vu",
            "uploader": "Anh Tuan Vu",
            "duration": 280.0,
        }
        is_match, score = self.resolver.validate_match(
            target_title="Ly Cà Phê Đắng",
            target_artist="Anh Vũ",
            candidate=candidate_tuan_vu,
            target_duration=280.0,
        )
        self.assertFalse(
            is_match,
            f"'Anh Vũ' không được phép khớp với 'Anh Tuan Vu'! (Score={score})",
        )
        self.assertLess(
            score,
            0.60,
            f"Điểm số khớp nghệ sĩ subset phải < 0.60, thực tế nhận được {score}",
        )

        # Ca sĩ trên YouTube: Ca sĩ Phi Thanh với tiêu đề chứa chữ 'Anh'
        candidate_phi_thanh = {
            "title": "Mùa Mưa Đi Qua - Phi Thanh | Anh dìu em về đường về nhà em qua phiến đá xanh xao",
            "uploader": "Giọng Ca Để Đời",
            "duration": 310.0,
        }
        is_match_pt, score_pt = self.resolver.validate_match(
            target_title="Mùa Mưa Đã Qua",
            target_artist="Anh Vũ",
            candidate=candidate_phi_thanh,
            target_duration=310.0,
        )
        self.assertFalse(
            is_match_pt,
            f"'Anh Vũ' không được phép khớp với kênh Giọng Ca Để Đời / Phi Thanh! (Score={score_pt})",
        )

    @patch.object(InputResolverService, "search_zingmp3")
    @patch.object(InputResolverService, "search_youtube")
    def test_resolve_track_prioritizes_zingmp3_before_youtube(
        self,
        mock_search_yt: MagicMock,
        mock_search_zing: MagicMock,
    ) -> None:
        """Hệ thống PHẢI ưu tiên tìm và lấy nguồn Zing MP3 nếu có bài chuẩn và không phải VIP."""
        # Giả lập Zing MP3 có bài chuẩn 'Ly Cà Phê Đắng' của 'Anh Vũ' (Free, status: 1)
        mock_search_zing.return_value = {
            "title": "Ly Cà Phê Đắng",
            "artist": "Anh Vũ",
            "duration": 245.0,
            "stream_url": "https://zingmp3.vn/bai-hat/Z9U0W99B.html",
            "is_vip": False,
            "match_score": 0.95,
        }

        track = self.resolver.resolve_track("Ly Cà Phê Đắng", artist="Anh Vũ")

        self.assertEqual(track.platform, "zingmp3")
        self.assertEqual(track.resolved_url, "https://zingmp3.vn/bai-hat/Z9U0W99B.html")
        self.assertTrue(track.is_verified_match)
        # Vì Zing MP3 đã khớp chuẩn, không được phép gọi search_youtube
        mock_search_yt.assert_not_called()

    def test_clean_forensic_metadata_strips_misleading_distributor_claims(self) -> None:
        """Hàm clean_forensic_metadata PHẢI gọt sạch các mác Topic, Hãng đĩa và Composer tự xưng."""
        raw_metadata = {
            "title": "Nhẫn Cỏ Đổi Vàng Son",
            "uploader": "GMHD - Topic",
            "channel": "GMHD - Topic",
            "description": (
                "Provided to YouTube by Symphonic Distribution\n"
                "Nhẫn Cỏ Đổi Vàng Son · GMHD\n"
                "℗ 2026 CELEB LABELS\n"
                "Released on: 2026-09-14\n"
                "Producer: CELEB LABELS Composer: Đoàn Khánh Hưng\n"
                "Auto-generated by YouTube."
            ),
            "target_artist": "GMHD",
            "target_title": "Nhẫn Cỏ Đổi Vàng Son",
        }

        cleaned = clean_forensic_metadata(raw_metadata)

        # Kênh - Topic phải được làm sạch thành tên nghệ sĩ trung tính
        self.assertNotIn("- Topic", cleaned.get("uploader", ""))
        self.assertNotIn("- Topic", cleaned.get("channel", ""))

        # Phần mô tả không được chứa 'Provided to YouTube by', 'Auto-generated', hoặc tên distributor
        cleaned_desc = cleaned.get("description", "")
        self.assertNotIn("Provided to YouTube by", cleaned_desc)
        self.assertNotIn("Auto-generated by YouTube", cleaned_desc)
        self.assertNotIn("Symphonic Distribution", cleaned_desc)
        self.assertNotIn("CELEB LABELS", cleaned_desc)


if __name__ == "__main__":
    unittest.main()
